package com.arshh.codemind.api;

import com.arshh.codemind.answering.AnswerService;
import com.arshh.codemind.common.RepositoryNotFoundException;
import com.arshh.codemind.common.RepositoryNotReadyException;
import com.arshh.codemind.dto.AskRequest;
import com.arshh.codemind.dto.AskResponse;
import com.arshh.codemind.dto.RepositoryRecord;
import com.arshh.codemind.dto.RepositoryStatus;
import com.arshh.codemind.dto.SearchResult;
import com.arshh.codemind.repository.RepositoryStateStore;
import com.arshh.codemind.retrieval.RetrievalService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import reactor.core.publisher.Flux;

import java.util.List;

/**
 * REST API for asking natural-language questions about an indexed repository.
 */
@RestController
@RequestMapping("/api/v1/repositories")
@Tag(name = "Ask", description = "Endpoints for grounded question answering with verified citations")
public class AskController {

    private final RepositoryStateStore repositoryStateStore;
    private final RetrievalService retrievalService;
    private final AnswerService answerService;

    public AskController(
            RepositoryStateStore repositoryStateStore,
            RetrievalService retrievalService,
            AnswerService answerService) {
        this.repositoryStateStore = repositoryStateStore;
        this.retrievalService = retrievalService;
        this.answerService = answerService;
    }

    /**
     * Answers questions grounded in the repository codebase, returning server-verified citations.
     */
    @PostMapping("/{id}/ask")
    @Operation(summary = "Ask question", description = "Asks a question about the repository and receives a grounded answer with citations")
    public ResponseEntity<AskResponse> askQuestion(
            @PathVariable("id") String id,
            @Valid @RequestBody AskRequest request) {

        // Verify repository exists
        RepositoryRecord record = repositoryStateStore.findById(id)
                .orElseThrow(() -> new RepositoryNotFoundException("Repository not found: " + id));

        // Refuse question answering if repository is still indexing or has failed
        if (record.status() != RepositoryStatus.READY) {
            throw new RepositoryNotReadyException("Repository is not ready for answering. Current status: " + record.status());
        }

        // Retrieve top matching code snippets using hybrid retrieval
        List<SearchResult> retrievedChunks = retrievalService.retrieve(id, request.question(), request.effectiveTopK());

        // Generate grounded answer and validate citations
        AskResponse response = answerService.answerQuestion(request.question(), retrievedChunks);

        return ResponseEntity.ok(response);
    }

    /**
     * Streams the grounded answer in real-time using Server-Sent Events (SSE).
     */
    @PostMapping(value = "/{id}/ask/stream", produces = MediaType.TEXT_EVENT_STREAM_VALUE)
    @Operation(summary = "Ask question (streaming)", description = "Streams tokens in real-time as they are generated by the LLM")
    public Flux<String> streamQuestion(
            @PathVariable("id") String id,
            @Valid @RequestBody AskRequest request) {

        RepositoryRecord record = repositoryStateStore.findById(id)
                .orElseThrow(() -> new RepositoryNotFoundException("Repository not found: " + id));

        if (record.status() != RepositoryStatus.READY) {
            throw new RepositoryNotReadyException("Repository is not ready for answering. Current status: " + record.status());
        }

        List<SearchResult> retrievedChunks = retrievalService.retrieve(id, request.question(), request.effectiveTopK());
        return answerService.streamAnswer(request.question(), retrievedChunks);
    }
}
